/// Which build a cancellation addresses. The build id is the sufficient,
/// documented selector. The client request id — the admission's
/// `Idempotency-Key` — is a recovery aid for an admission whose response was
/// lost; it resolves through the project's request-id index and never admits
/// anything.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CancelBuildSelector {
    BuildId(String),
    ClientRequestId(String),
}

impl CancelBuildSelector {
    pub(crate) fn body(&self) -> Value {
        match self {
            Self::BuildId(build_id) => serde_json::json!({ "build_id": build_id }),
            Self::ClientRequestId(id) => serde_json::json!({ "client_request_id": id }),
        }
    }
}

wire_enum! {
    /// What the service observed when asked to cancel.
    CancelBuildOutcome {
        /// The cancellation decision is durable. The build will not publish.
        Cancelled => "cancelled",
        AlreadyCancelled => "already_cancelled",
        /// Publication won: the build's result stands.
        AlreadyCompleted => "already_completed",
        AlreadyFailed => "already_failed",
        /// No build is indexed under the client request id. An observation of
        /// absence, not a promise: a delayed original admission may still
        /// create the build.
        NotAdmitted => "not_admitted",
    }
}

/// The service's answer to a cancellation.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CancelBuildResponse {
    pub outcome: CancelBuildOutcome,
    /// The build as observed, absent for `not_admitted`.
    #[serde(default)]
    pub build: Option<ImageBuildInfo>,
}

/// An explicit interruption request for a CAS operation.
///
/// Triggering it while [`start_build`], [`start_import`] or
/// [`ImageBuildHandle::wait`] is running stops the operation locally and
/// runs the bounded remote cancellation handshake. Dropping the signal, or a
/// handle, does nothing remotely.
#[derive(Debug, Clone, Default)]
pub struct InterruptSignal {
    token: tokio_util::sync::CancellationToken,
}

impl InterruptSignal {
    pub fn new() -> Self {
        Self::default()
    }

    /// Request cancellation. Idempotent.
    pub fn trigger(&self) {
        self.token.cancel();
    }

    pub fn is_triggered(&self) -> bool {
        self.token.is_cancelled()
    }

    /// Resolves once the signal is triggered.
    pub async fn triggered(&self) {
        self.token.cancelled().await
    }
}

/// How an explicit interruption ended.
#[derive(Debug, Clone, PartialEq)]
pub enum InterruptionOutcome {
    /// Confirmed: the build is admitted and the cancellation is durable.
    Cancelled,
    /// Publication won the race; the build's result stands.
    AlreadyCompleted(Option<Box<ImageBuildResult>>),
    AlreadyCancelled,
    AlreadyFailed(Option<String>),
    /// The admission was unresolved and the service has nothing under the
    /// client request id. Not a confirmation: a delayed admission may still
    /// create the build, which can then be cancelled by the request id.
    NotAdmitted,
    /// The handshake ran out of its budget without a durable answer.
    Unconfirmed(String),
}

/// What an interrupted operation reports: the build id when admission
/// resolved, the client request id while it did not, and the outcome.
#[derive(Debug, Clone, PartialEq)]
pub struct InterruptionReport {
    pub build_id: Option<String>,
    pub client_request_id: Option<String>,
    pub outcome: InterruptionOutcome,
}

impl InterruptionOutcome {
    /// A stable machine-readable name for bindings.
    pub fn name(&self) -> &'static str {
        match self {
            Self::Cancelled => "cancelled",
            Self::AlreadyCompleted(_) => "already_completed",
            Self::AlreadyCancelled => "already_cancelled",
            Self::AlreadyFailed(_) => "already_failed",
            Self::NotAdmitted => "not_admitted",
            Self::Unconfirmed(_) => "unconfirmed",
        }
    }
}

impl InterruptionReport {
    /// Whether the remote operation is confirmed not to publish: cancelled
    /// now or earlier, or already failed.
    pub fn is_confirmed_cancelled(&self) -> bool {
        matches!(
            self.outcome,
            InterruptionOutcome::Cancelled
                | InterruptionOutcome::AlreadyCancelled
                | InterruptionOutcome::AlreadyFailed(_)
        )
    }
}

impl fmt::Display for InterruptionReport {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let build = self.build_id.as_deref();
        match &self.outcome {
            InterruptionOutcome::Cancelled => {
                write!(f, "Build {} cancelled", build.unwrap_or("-"))
            }
            InterruptionOutcome::AlreadyCompleted(result) => {
                write!(f, "Build {} already completed", build.unwrap_or("-"))?;
                if let Some(result) = result {
                    write!(
                        f,
                        " (image '{}', {})",
                        result.name.as_deref().unwrap_or("-"),
                        result.id.as_deref().unwrap_or("-")
                    )?;
                }
                Ok(())
            }
            InterruptionOutcome::AlreadyCancelled => {
                write!(f, "Build {} was already cancelled", build.unwrap_or("-"))
            }
            InterruptionOutcome::AlreadyFailed(error) => {
                write!(f, "Build {} had already failed", build.unwrap_or("-"))?;
                if let Some(error) = error {
                    write!(f, ": {error}")?;
                }
                Ok(())
            }
            InterruptionOutcome::NotAdmitted => write!(
                f,
                "No build was admitted for client request id {}; a delayed admission may still \
                 create one, which can be cancelled by that request id",
                self.client_request_id.as_deref().unwrap_or("-")
            ),
            InterruptionOutcome::Unconfirmed(reason) => match (build, &self.client_request_id) {
                (Some(build_id), _) => write!(
                    f,
                    "Cancellation of build {build_id} was not confirmed: {reason}"
                ),
                (None, Some(request_id)) => write!(
                    f,
                    "Cancellation of the build admitted with client request id {request_id} was \
                     not confirmed: {reason}"
                ),
                (None, None) => write!(f, "Cancellation was not confirmed: {reason}"),
            },
        }
    }
}

