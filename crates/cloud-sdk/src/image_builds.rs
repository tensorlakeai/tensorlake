macro_rules! wire_enum {
    (
        $(#[$meta:meta])*
        $name:ident { $($(#[$variant_meta:meta])* $variant:ident => $wire:literal),+ $(,)? }
    ) => {
        $(#[$meta])*
        #[derive(Debug, Clone, PartialEq, Eq, Hash)]
        pub enum $name {
            $($(#[$variant_meta])* $variant,)+
            /// A value this SDK does not know; newer services may add some.
            Unknown(String),
        }

        impl $name {
            /// The wire spelling.
            pub fn as_str(&self) -> &str {
                match self {
                    $(Self::$variant => $wire,)+
                    Self::Unknown(value) => value.as_str(),
                }
            }
        }

        impl From<String> for $name {
            fn from(value: String) -> Self {
                match value.as_str() {
                    $($wire => Self::$variant,)+
                    _ => Self::Unknown(value),
                }
            }
        }

        impl From<&str> for $name {
            fn from(value: &str) -> Self {
                Self::from(value.to_string())
            }
        }

        impl From<$name> for String {
            fn from(value: $name) -> Self {
                value.as_str().to_string()
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(self.as_str())
            }
        }

        impl Serialize for $name {
            fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                serializer.serialize_str(self.as_str())
            }
        }

        impl<'de> Deserialize<'de> for $name {
            fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                Ok(Self::from(String::deserialize(deserializer)?))
            }
        }
    };
}

wire_enum! {
    /// The lifecycle status of a build. `Succeeded`, `Failed` and `Cancelled`
    /// are terminal; failed and cancelled are distinct outcomes.
    ImageBuildStatus {
        Pending => "pending",
        Running => "running",
        Succeeded => "succeeded",
        Failed => "failed",
        Cancelled => "cancelled",
    }
}

impl ImageBuildStatus {
    /// Whether the build will not change any more.
    pub fn is_terminal(&self) -> bool {
        matches!(self, Self::Succeeded | Self::Failed | Self::Cancelled)
    }
}

wire_enum! {
    /// Where an unfinished build is in its workflow.
    ImageBuildPhase {
        AwaitingContext => "awaiting_context",
        StartingBuilder => "starting_builder",
        Executing => "executing",
        Snapshotting => "snapshotting",
        Publishing => "publishing",
        Finished => "finished",
    }
}

wire_enum! {
    /// What kind of operation a build record is.
    ImageBuildKind {
        Import => "import",
        Dockerfile => "dockerfile",
        /// A direct publication (`POST /images`, `POST /images/from-snapshot`)
        /// that outlived its bounded inline wait.
        Direct => "direct",
    }
}

/// Where a Dockerfile build uploads its context, issued at admission (and
/// re-issued on an exact replay) while the context is unsealed. Carried by
/// the admission response only; it never appears on [`ImageBuildInfo`], so
/// no `info()` output, `--json` print or binding record leaks the signed URL.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ContextUploadCapability {
    pub url: String,
    #[serde(default)]
    pub max_bytes: Option<u64>,
}

/// One CAS image build or import, as the CAS image API reports it (the twelve-field
/// `BuildInfo`). Unknown fields are ignored so newer services remain
/// readable.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ImageBuildInfo {
    pub build_id: String,
    #[serde(default = "unknown_kind")]
    pub kind: ImageBuildKind,
    /// The image name the operation publishes.
    #[serde(default)]
    pub name: Option<String>,
    #[serde(default = "unknown_status")]
    pub status: ImageBuildStatus,
    #[serde(default)]
    pub phase: Option<ImageBuildPhase>,
    /// Builder executions so far.
    #[serde(default)]
    pub attempt_no: u64,
    /// The builder sandbox of the active attempt, while the build is running.
    #[serde(default)]
    pub builder_sandbox_id: Option<String>,
    /// When the service gives the whole operation up, as epoch milliseconds.
    /// The SDK adds [`DEPLOYMENT_RECOVERY_ALLOWANCE`] when bounding a wait.
    #[serde(default)]
    pub operation_deadline_ms: Option<u64>,
    #[serde(default)]
    pub created_at_ms: Option<u64>,
    #[serde(default)]
    pub updated_at_ms: Option<u64>,
    /// The immutable publication result of a succeeded build, in the
    /// template shape (decoded from the service's trimmed record).
    #[serde(default, deserialize_with = "deserialize_result")]
    pub result: Option<ImageBuildResult>,
    #[serde(default)]
    pub error: Option<String>,
}

/// The service reports `result` as its trimmed image record; the SDK keeps
/// the template-shaped projection of it.
fn deserialize_result<'de, D>(deserializer: D) -> Result<Option<ImageBuildResult>, D::Error>
where
    D: serde::Deserializer<'de>,
{
    let wire: Option<ImageServiceImage> = Option::deserialize(deserializer)?;
    Ok(wire.map(ImageServiceImage::into_template))
}

fn unknown_kind() -> ImageBuildKind {
    ImageBuildKind::Unknown(String::new())
}

fn unknown_status() -> ImageBuildStatus {
    ImageBuildStatus::Unknown(String::new())
}

impl ImageBuildInfo {
    /// Decode a service build record, ignoring fields this SDK does not know.
    pub fn from_json(value: Value) -> Result<Self, serde_json::Error> {
        serde_json::from_value(value)
    }

    /// The service-informed wall-clock bound on this operation, with the
    /// deployment-recovery allowance added. `None` when the service reports
    /// no deadline.
    pub fn operation_deadline(&self) -> Option<SystemTime> {
        self.operation_deadline_ms
            .map(|ms| UNIX_EPOCH + Duration::from_millis(ms) + DEPLOYMENT_RECOVERY_ALLOWANCE)
    }
}

