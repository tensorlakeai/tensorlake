//! CAS image build operations: start, get, wait and cancel a CAS image
//! build or import as a first-class operation (ADR 0107).
//!
//! # Scope: CAS only
//!
//! Everything in this module addresses the build operations of CAS
//! (content-addressed streaming) images. Legacy images — `tl sbx image
//! create`/`import` with `--no-cas`, `sandbox_template_` ids, `.tlsnap`
//! snapshots — have no build operation here: [`start_build`] and
//! [`start_import`] refuse options whose `cas` flag is off, and a
//! `sandbox_template_` reference is never looked up as a build id. The legacy
//! paths keep their own requests, outputs, errors and interruption behavior.
//!
//! # Operations
//!
//! - [`start_build`] / [`start_import`] admit a build and, for a Dockerfile
//!   build, upload and seal the context. They return an [`ImageBuildHandle`]
//!   without waiting, so a caller may leave the operation running.
//! - [`ImageBuildClient::get`] looks a build up by its service-generated id.
//! - [`ImageBuildHandle::refresh`] re-reads the current [`ImageBuildInfo`].
//! - [`ImageBuildHandle::wait`] polls the build to a terminal status and
//!   returns its immutable [`ImageBuildResult`] (`BuildInfo.result`). The
//!   mutable image record is never consulted to infer this build's result, so
//!   a wait returns the right answer even after the image was rebuilt.
//! - [`ImageBuildHandle::cancel`] / [`ImageBuildClient::cancel`] cancel by
//!   build id. The build id alone is sufficient: admission returns it, the CLI
//!   prints it, and `GET /builds/{id}` and the `image_build_in_progress`
//!   conflict expose it. [`CancelBuildSelector::ClientRequestId`] exists only
//!   to recover an admission whose response was lost.
//!
//! # Admission and request ids
//!
//! Every admission (`POST /builds`, `POST /images/from-snapshot`) carries an
//! opaque client request id in the `Idempotency-Key` header, generated by
//! [`new_client_request_id`] before the first attempt and retained across
//! transport retries; it is never re-minted to retry. An exact replay returns
//! the same operation. A different request for a name that already has an
//! unfinished operation is refused with [`ImageBuildError::InProgress`]; the
//! SDK never cancels or supersedes that operation on its own.
//!
//! # Waiting, deadlines and reconnects
//!
//! Status polling reconnects after transport failures, 408/429 and 5xx with
//! bounded exponential backoff, jitter and `Retry-After`, reporting each
//! reconnect as a `Status` event. Authorization, validation and not-found
//! answers are not retried. The overall wait is bounded by the
//! service-reported operation deadline plus a deployment-recovery allowance
//! ([`DEPLOYMENT_RECOVERY_ALLOWANCE`]), by an optional caller timeout
//! ([`ImageBuildWaitOptions::timeout`]), and, when the service reports no
//! deadline and the caller sets none, by [`DEFAULT_WAIT_LIMIT`]. A timeout is
//! reported as [`ImageBuildError::Timeout`] carrying the build id: the
//! operation may still be running, and it is neither failed nor cancelled by
//! the client. Every deadline bounds the requests in flight as well as the
//! retries and sleeps between them: a request the service never answers is
//! abandoned at the deadline (or after a per-request bound), so a stalled
//! connection cannot hold a wait, a lookup or the cancellation handshake
//! past its budget. [`ImageBuildClient::wait_build`] runs the initial lookup
//! inside the same interruptible, timeout-bounded operation as the wait.
//! Builder logs are followed through the sandbox API as a courtesy: losing
//! them is a warning, not the end of the wait.
//!
//! # Interruption
//!
//! Disconnecting, dropping a handle, or a process crash never cancels the
//! remote operation. Explicit interruption does: an [`InterruptSignal`]
//! triggered during [`start_build`], [`start_import`] or
//! [`ImageBuildHandle::wait`] runs a bounded cancellation handshake
//! ([`CANCEL_HANDSHAKE_BUDGET`]) and reports the outcome as
//! [`ImageBuildError::Interrupted`]: confirmed cancellation, already
//! completed, or an unconfirmed acknowledgement with the build id (or, while
//! admission is unresolved, the client request id). Only an admitted build
//! with a durable acknowledgement counts as cancelled; a `not_admitted`
//! observation is not confirmation.
//!
//! # Image ids are mutable
//!
//! An image name and its `image_` id name the *current* image; a rebuild
//! replaces what they point at. The build id and its [`ImageBuildResult`]
//! are the immutable record of one operation.

