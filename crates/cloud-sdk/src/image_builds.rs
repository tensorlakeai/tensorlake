/// The `409 image_build_in_progress` conflict: the name already has an
/// unfinished operation. Cancel it (by `active_build_id`) before starting
/// another; the SDK never does so automatically.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ImageBuildConflict {
    pub image_name: Option<String>,
    pub active_build_id: Option<String>,
    pub active_kind: Option<ImageBuildKind>,
    pub active_status: Option<ImageBuildStatus>,
    /// The service's message, which names the kind and status.
    pub message: String,
}

impl fmt::Display for ImageBuildConflict {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.message)
    }
}

/// Everything a build operation can fail with. Terminal service outcomes
/// (`Failed`, `Cancelled`) are distinct from the client giving up
/// (`Timeout`) and from an explicit interruption (`Interrupted`).
#[derive(Debug, thiserror::Error)]
pub enum ImageBuildError {
    #[error("{0}")]
    Usage(String),
    #[error("{0}")]
    Auth(String),
    /// Unknown, foreign or retired: a finished build is kept only while it
    /// is its image's current build; a later build of the image or deleting
    /// the image retires it (ADR 0108).
    #[error(
        "build {build_id} not found: finished builds are kept only while they are their image's \
         current build; a later build of the image or deleting the image retires them"
    )]
    NotFound { build_id: String },
    #[error("{0}")]
    InProgress(ImageBuildConflict),
    #[error(
        "client request id {client_request_id} was already used for a different request: {message}"
    )]
    IdempotencyKeyReused {
        client_request_id: String,
        message: String,
    },
    #[error("build {build_id} failed: {error}")]
    Failed {
        build_id: String,
        error: String,
        info: Box<ImageBuildInfo>,
    },
    #[error("build {build_id} was cancelled")]
    Cancelled {
        build_id: String,
        info: Box<ImageBuildInfo>,
    },
    /// The client stopped waiting. The operation may still be running; it was
    /// neither failed nor cancelled.
    #[error(
        "build {build_id} did not finish within {}s of waiting; it may still be running (check it \
         by build id)",
        waited.as_secs()
    )]
    Timeout { build_id: String, waited: Duration },
    #[error("{0}")]
    Interrupted(InterruptionReport),
    #[error("CAS image API request failed (HTTP {status}): {message}")]
    Service { status: u16, message: String },
    #[error("{0}")]
    Sdk(#[from] SdkError),
    #[error("IO error: {0}")]
    Io(#[from] std::io::Error),
    #[error("{0}")]
    Json(#[from] serde_json::Error),
    #[error("{0}")]
    Other(String),
}

impl ImageBuildError {
    pub(crate) fn other(message: impl Into<String>) -> Self {
        Self::Other(message.into())
    }

    pub(crate) fn usage(message: impl Into<String>) -> Self {
        Self::Usage(message.into())
    }

    /// The build id this error is about, when one is known.
    pub fn build_id(&self) -> Option<&str> {
        match self {
            Self::NotFound { build_id }
            | Self::Failed { build_id, .. }
            | Self::Cancelled { build_id, .. }
            | Self::Timeout { build_id, .. } => Some(build_id),
            Self::Interrupted(report) => report.build_id.as_deref(),
            Self::InProgress(conflict) => conflict.active_build_id.as_deref(),
            _ => None,
        }
    }

    /// The structured form the Python and Node bindings expose: `code`,
    /// `message`, `build_id`, and the outcome-specific fields (conflict
    /// details, the failure error and record, the interruption outcome).
    pub fn to_json(&self) -> Value {
        let mut payload = serde_json::json!({
            "code": self.code(),
            "message": self.to_string(),
            "build_id": self.build_id(),
        });
        let object = payload.as_object_mut().expect("object");
        match self {
            Self::InProgress(conflict) => {
                object.insert("image_name".into(), serde_json::json!(conflict.image_name));
                object.insert(
                    "active_build_id".into(),
                    serde_json::json!(conflict.active_build_id),
                );
                object.insert(
                    "active_kind".into(),
                    serde_json::json!(conflict.active_kind.as_ref().map(ImageBuildKind::as_str)),
                );
                object.insert(
                    "active_status".into(),
                    serde_json::json!(
                        conflict
                            .active_status
                            .as_ref()
                            .map(ImageBuildStatus::as_str)
                    ),
                );
            }
            Self::IdempotencyKeyReused {
                client_request_id, ..
            } => {
                object.insert(
                    "client_request_id".into(),
                    serde_json::json!(client_request_id),
                );
            }
            Self::Failed { error, info, .. } => {
                object.insert("error".into(), serde_json::json!(error));
                object.insert(
                    "info".into(),
                    serde_json::to_value(info).unwrap_or(Value::Null),
                );
            }
            Self::Cancelled { info, .. } => {
                object.insert(
                    "info".into(),
                    serde_json::to_value(info).unwrap_or(Value::Null),
                );
            }
            Self::Timeout { waited, .. } => {
                object.insert("waited_secs".into(), serde_json::json!(waited.as_secs()));
            }
            Self::Interrupted(report) => {
                object.insert(
                    "client_request_id".into(),
                    serde_json::json!(report.client_request_id),
                );
                object.insert("outcome".into(), serde_json::json!(report.outcome.name()));
                object.insert(
                    "confirmed".into(),
                    serde_json::json!(report.is_confirmed_cancelled()),
                );
                if let InterruptionOutcome::AlreadyCompleted(Some(result)) = &report.outcome {
                    object.insert(
                        "result".into(),
                        serde_json::to_value(result).unwrap_or(Value::Null),
                    );
                }
            }
            Self::Service { status, .. } => {
                object.insert("status".into(), serde_json::json!(status));
            }
            _ => {}
        }
        payload
    }

    /// A stable machine-readable code for bindings.
    pub fn code(&self) -> &'static str {
        match self {
            Self::Usage(_) => "usage",
            Self::Auth(_) => "auth",
            Self::NotFound { .. } => "not_found",
            Self::InProgress(_) => "image_build_in_progress",
            Self::IdempotencyKeyReused { .. } => "client_request_id_mismatch",
            Self::Failed { .. } => "failed",
            Self::Cancelled { .. } => "cancelled",
            Self::Timeout { .. } => "timeout",
            Self::Interrupted(_) => "interrupted",
            Self::Service { .. } => "service",
            Self::Sdk(_) | Self::Io(_) | Self::Json(_) | Self::Other(_) => "internal",
        }
    }
}

impl From<SandboxImageBuildError> for ImageBuildError {
    fn from(error: SandboxImageBuildError) -> Self {
        match error {
            SandboxImageBuildError::Build(error) => error,
            SandboxImageBuildError::Usage(message) => Self::Usage(message),
            SandboxImageBuildError::Auth(message) => Self::Auth(message),
            SandboxImageBuildError::Http(error) => Self::Sdk(SdkError::Http(error)),
            SandboxImageBuildError::Io(error) => Self::Io(error),
            SandboxImageBuildError::Json(error) => Self::Json(error),
            SandboxImageBuildError::Sdk(error) => Self::Sdk(error),
            other => Self::Other(other.to_string()),
        }
    }
}

