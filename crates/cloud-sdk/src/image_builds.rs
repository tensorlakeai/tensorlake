/// Credentials and scope for build operations. The same rules as the
/// convenience builders: API keys are self-scoping; a personal access token
/// (`use_scope_headers`) needs the organization and project.
#[derive(Debug, Clone)]
pub struct ImageBuildClientOptions {
    pub api_url: String,
    pub bearer_token: String,
    pub use_scope_headers: bool,
    pub organization_id: Option<String>,
    pub project_id: Option<String>,
    /// The sandbox namespace builder logs are followed in.
    pub namespace: String,
    pub user_agent: Option<String>,
}

/// How long [`ImageBuildHandle::wait`] waits and what it follows.
#[derive(Debug, Clone, Default)]
pub struct ImageBuildWaitOptions {
    /// A caller bound on the wait, applied on top of the service-informed
    /// deadline. Expiry raises [`ImageBuildError::Timeout`] and leaves the
    /// operation running.
    pub timeout: Option<Duration>,
    /// Follow `tl-image-builder` output from the builder sandbox while an
    /// attempt is running. Off by default for non-interactive callers.
    pub follow_logs: bool,
}

/// A client for looking up and cancelling builds by id.
#[derive(Clone)]
pub struct ImageBuildClient {
    pub(crate) client: crate::Client,
    pub(crate) ctx: ResolvedBuildContext,
}

impl ImageBuildClient {
    pub fn new(options: ImageBuildClientOptions) -> Result<Self, ImageBuildError> {
        image_service_builds::image_build_client(options)
    }

    /// Look a build up by its service-generated id. Unknown and foreign builds
    /// are the same [`ImageBuildError::NotFound`]. A `sandbox_template_` or
    /// `image_` reference is refused locally: it is not a build id.
    pub async fn get(&self, build_id: &str) -> Result<ImageBuildHandle, ImageBuildError> {
        reject_legacy_reference(build_id)?;
        let info = image_service_builds::get_build(&self.client, build_id).await?;
        Ok(ImageBuildHandle {
            client: self.clone(),
            build_id: info.build_id.clone(),
            // The service no longer reports the admission key; a handle from
            // a lookup cancels by build id, which is the sufficient selector.
            client_request_id: None,
            info,
        })
    }

    /// Look `build_id` up and wait for it in one interruptible operation:
    /// [`Self::get`] followed by [`ImageBuildHandle::wait`], with the lookup
    /// itself under `interrupt` and under `options.timeout`. Ctrl+C during a
    /// slow or stalled first request therefore cancels the build (its id is
    /// the sufficient selector) rather than ending the process silently,
    /// and a short timeout bounds the lookup too.
    pub async fn wait_build<F>(
        &self,
        build_id: &str,
        options: ImageBuildWaitOptions,
        interrupt: &InterruptSignal,
        emit: F,
    ) -> Result<ImageBuildResult, ImageBuildError>
    where
        F: FnMut(SandboxImageBuildEvent),
    {
        reject_legacy_reference(build_id)?;
        let info = image_service_builds::lookup_and_wait(
            &self.client,
            Some(&self.ctx),
            build_id,
            &options,
            interrupt,
            emit,
        )
        .await?;
        image_service_builds::terminal_result(&info)
    }

    /// Cancel one build, bounded by [`CANCEL_HANDSHAKE_BUDGET`]. The outcome
    /// says what the service observed; `not_admitted` is not a cancellation.
    pub async fn cancel(
        &self,
        selector: CancelBuildSelector,
    ) -> Result<CancelBuildResponse, ImageBuildError> {
        if let CancelBuildSelector::BuildId(build_id) = &selector {
            reject_legacy_reference(build_id)?;
        }
        image_service_builds::cancel_build(&self.client, &selector, CANCEL_HANDSHAKE_BUDGET).await
    }
}

/// One admitted build. Stores the build identity and the caller's context;
/// dropping it performs no network I/O.
#[derive(Clone)]
pub struct ImageBuildHandle {
    pub(crate) client: ImageBuildClient,
    pub(crate) build_id: String,
    pub(crate) client_request_id: Option<String>,
    pub(crate) info: ImageBuildInfo,
}

impl ImageBuildHandle {
    pub fn build_id(&self) -> &str {
        &self.build_id
    }

    /// The admission's client request id, when this handle started the build
    /// or the service reports it. Not needed to cancel.
    pub fn client_request_id(&self) -> Option<&str> {
        self.client_request_id.as_deref()
    }

    /// The last observed state.
    pub fn info(&self) -> &ImageBuildInfo {
        &self.info
    }

    /// Re-read the current state.
    pub async fn refresh(&mut self) -> Result<&ImageBuildInfo, ImageBuildError> {
        self.info = image_service_builds::get_build(&self.client.client, &self.build_id).await?;
        Ok(&self.info)
    }

    /// Poll to a terminal status and return the build's immutable result.
    /// `interrupt` triggers the remote cancellation handshake; see the module
    /// docs for deadlines and reconnects.
    pub async fn wait<F>(
        &mut self,
        options: ImageBuildWaitOptions,
        interrupt: &InterruptSignal,
        emit: F,
    ) -> Result<ImageBuildResult, ImageBuildError>
    where
        F: FnMut(SandboxImageBuildEvent),
    {
        let info = image_service_builds::wait_for_terminal(
            &self.client.client,
            Some(&self.client.ctx),
            &self.build_id,
            self.client_request_id.as_deref(),
            Some(self.info.clone()),
            &options,
            interrupt,
            emit,
        )
        .await?;
        self.info = info;
        image_service_builds::terminal_result(&self.info)
    }

    /// Cancel this build by its id.
    pub async fn cancel(&self) -> Result<CancelBuildResponse, ImageBuildError> {
        self.client
            .cancel(CancelBuildSelector::BuildId(self.build_id.clone()))
            .await
    }
}

/// Admit a Dockerfile build and upload and seal its context, without
/// waiting. `options.common.cas` must be set: legacy builds have no build
/// operation. `docker_config_json` is forwarded as for the convenience
/// builders. The returned handle's info is the admission response.
pub async fn start_build<F>(
    options: SandboxImageBuildOptions,
    docker_config_json: Option<String>,
    interrupt: &InterruptSignal,
    emit: F,
) -> Result<ImageBuildHandle, ImageBuildError>
where
    F: FnMut(SandboxImageBuildEvent),
{
    crate::sandbox_images::start_cas_build(options, docker_config_json, interrupt, emit).await
}

/// Admit a registry import without waiting. `options.common.cas` must be
/// set.
pub async fn start_import<F>(
    options: SandboxImageImportOptions,
    docker_config_json: Option<String>,
    interrupt: &InterruptSignal,
    emit: F,
) -> Result<ImageBuildHandle, ImageBuildError>
where
    F: FnMut(SandboxImageBuildEvent),
{
    crate::sandbox_images::start_cas_import(options, docker_config_json, interrupt, emit).await
}

/// New operations address the CAS image registry only. A reference that is
/// positively a legacy template id, or an image id rather than a build id,
/// is refused before any request.
pub(crate) fn reject_legacy_reference(build_id: &str) -> Result<(), ImageBuildError> {
    let build_id = build_id.trim();
    if build_id.is_empty() {
        return Err(ImageBuildError::usage("build id must not be empty"));
    }
    if build_id.starts_with(crate::sandbox_image_catalog::SANDBOX_TEMPLATE_ID_PREFIX) {
        return Err(ImageBuildError::usage(format!(
            "'{build_id}' is a legacy image id; legacy images have no build operation to \
             get, wait for or cancel"
        )));
    }
    if build_id.starts_with(crate::sandbox_image_catalog::IMAGE_SERVICE_ID_PREFIX) {
        return Err(ImageBuildError::usage(format!(
            "'{build_id}' is a CAS image id, not a build id; look the CAS image up with \
             describe, or use the build id admission returned"
        )));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A missing build is the same error whether it never existed, belongs to
    /// another project or was retired; the message says why a known id can
    /// stop resolving (ADR 0108 retirement).
    #[test]
    fn not_found_explains_retirement() {
        let error = ImageBuildError::NotFound {
            build_id: "build-x".to_string(),
        };
        let message = error.to_string();
        assert!(message.starts_with("build build-x not found"), "{message}");
        assert!(message.contains("current build"), "{message}");
        assert!(message.contains("retires them"), "{message}");
        assert_eq!(error.code(), "not_found");
        assert_eq!(error.build_id(), Some("build-x"));
    }

    #[test]
    fn client_request_ids_are_32_hex_and_validate() {
        let id = new_client_request_id();
        assert_eq!(id.len(), 32);
        assert!(
            id.bytes()
                .all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase())
        );
        assert_ne!(id, new_client_request_id());
        validate_client_request_id(&id).unwrap();
        assert!(validate_client_request_id("").is_err());
        assert!(validate_client_request_id(&"a".repeat(129)).is_err());
        assert!(validate_client_request_id("has space").is_err());
        validate_client_request_id("opaque-Key_1").unwrap();
    }

    #[test]
    fn build_info_ignores_unknown_fields_and_keeps_unknown_enum_values() {
        let info = ImageBuildInfo::from_json(serde_json::json!({
            "build_id": "build-1",
            "kind": "dockerfile",
            "status": "paused",
            "phase": "warming",
            "future_field": {"x": 1},
            "result": null,
            "cleanup_pending": true,
            "context_upload": {"url": "https://upload.test/ctx", "max_bytes": 8192},
            "operation_deadline_ms": 1_000,
        }))
        .unwrap();
        assert_eq!(info.status, ImageBuildStatus::Unknown("paused".to_string()));
        assert_eq!(
            info.phase,
            Some(ImageBuildPhase::Unknown("warming".to_string()))
        );
        // Removed pre-trim fields and the upload capability are not part of
        // the record: `info()` output never carries the signed URL.
        let json = serde_json::to_value(&info).unwrap();
        assert!(json.get("cleanup_pending").is_none(), "{json}");
        assert!(json.get("context_upload").is_none(), "{json}");
        assert!(!json.to_string().contains("upload.test"), "{json}");
        assert_eq!(
            info.operation_deadline(),
            Some(UNIX_EPOCH + Duration::from_millis(1_000) + DEPLOYMENT_RECOVERY_ALLOWANCE)
        );
        assert_eq!(
            serde_json::to_value(&info.status).unwrap(),
            Value::String("paused".to_string())
        );
        assert!(!ImageBuildStatus::Running.is_terminal());
        assert!(ImageBuildStatus::Cancelled.is_terminal());
    }

    #[test]
    fn legacy_references_are_refused_before_any_request() {
        assert!(reject_legacy_reference("sandbox_template_1").is_err());
        assert!(reject_legacy_reference("image_abc").is_err());
        assert!(reject_legacy_reference("  ").is_err());
        reject_legacy_reference("build-1").unwrap();
    }

    #[test]
    fn interruption_reports_distinguish_not_admitted_from_cancelled() {
        let report = InterruptionReport {
            build_id: None,
            client_request_id: Some("rid".to_string()),
            outcome: InterruptionOutcome::NotAdmitted,
        };
        assert!(!report.is_confirmed_cancelled());
        assert!(report.to_string().contains("No build was admitted"));
        let report = InterruptionReport {
            build_id: Some("build-1".to_string()),
            client_request_id: None,
            outcome: InterruptionOutcome::Cancelled,
        };
        assert!(report.is_confirmed_cancelled());
        assert_eq!(report.to_string(), "Build build-1 cancelled");
    }
}
